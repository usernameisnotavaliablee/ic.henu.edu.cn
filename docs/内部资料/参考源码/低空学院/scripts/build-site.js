function buildPage(fileName) {
  const page = site.pages[fileName];
  const content = page.type === "overview"
    ? fs.readFileSync(path.join(srcDir, "content", "overview", fileName), "utf8").trim()
    : detailPages[fileName]?.content;
  if (!content) throw new Error(`No content for ${fileName}`);
  const pageBody = render(read("templates/page.html"), { content });
  return render(read("templates/document.html"), {
    fileName,
    title: page.title,
    description: page.description,
    cssHref: page.cssHref || "css/style.css",
    bodyClass: page.bodyClass ? ` class="${page.bodyClass}"` : "",
    page: pageBody,
  });
}

