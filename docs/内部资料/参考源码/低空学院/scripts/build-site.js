const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "src");
const distDir = path.join(root, "dist");
const site = require(path.join(srcDir, "data", "site.js"));
const detailPages = require(path.join(srcDir, "data", "detail-pages.js"));

