function copyDirectory(name) {
  fs.cpSync(path.join(srcDir, name), path.join(distDir, name), { recursive: true });
}

function writeSiteShell() {
  fs.mkdirSync(path.join(distDir, "js"), { recursive: true });
  fs.writeFileSync(path.join(distDir, "js", "site-shell.js"), buildSiteShellSource(), "utf8");
}

function buildFullSite() {
  fs.rmSync(distDir, { recursive: true, force: true });
  fs.mkdirSync(distDir, { recursive: true });
  for (const fileName of Object.keys(site.pages).sort()) {
    fs.writeFileSync(path.join(distDir, fileName), buildPage(fileName), "utf8");
  }
  for (const asset of ["css", "js", "assets"]) copyDirectory(asset);
  writeSiteShell();
  for (const fileName of ["robots.txt", "sitemap.xml", "cf944f0ebed08f37dac4eb97a80c2662.txt"]) {
    fs.copyFileSync(path.join(root, fileName), path.join(distDir, fileName));
  }
  console.log(`Built ${Object.keys(site.pages).length} HTML pages into dist/.`);
  console.log("Deploy: upload all contents of dist/ to the site root.");
}

function buildSinglePage(fileName) {
  if (!site.pages[fileName]) throw new Error(`Unknown page: ${fileName}`);
  fs.mkdirSync(distDir, { recursive: true });
  fs.writeFileSync(path.join(distDir, fileName), buildPage(fileName), "utf8");
  console.log(`Built ${fileName}.`);
  console.log(`Deploy only: dist/${fileName} -> site root/${fileName}`);
}

function buildSharedShell() {
  writeSiteShell();
  console.log("Built shared header/footer shell.");
  console.log("Deploy only: dist/js/site-shell.js -> site root/js/site-shell.js");
}

function copySingleStaticFile(relativePath) {
  const normalized = relativePath.replace(/\\/g, "/").replace(/^\.\//, "");
  if (!/^(?:css|js|assets)\//.test(normalized) || normalized === "js/site-shell.js") {
    throw new Error("--static accepts a file below css/, js/, or assets/ (except generated js/site-shell.js)");
  }
  const sourcePath = path.resolve(srcDir, normalized);
  const sourceRelative = path.relative(srcDir, sourcePath);
  if (sourceRelative.startsWith("..") || path.isAbsolute(sourceRelative) || !fs.statSync(sourcePath).isFile()) {
    throw new Error(`Invalid static file: ${relativePath}`);
  }
  const outputPath = path.join(distDir, normalized);
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.copyFileSync(sourcePath, outputPath);
  console.log(`Copied static file ${normalized}.`);
  console.log(`Deploy only: dist/${normalized} -> site root/${normalized}`);
}

function main(args) {
  if (!args.length) return buildFullSite();
  if (args.length === 1 && args[0] === "--shared") return buildSharedShell();
  if (args.length === 2 && args[0] === "--page") return buildSinglePage(args[1]);
  if (args.length === 2 && args[0] === "--static") return copySingleStaticFile(args[1]);
  throw new Error("Usage: node scripts/build-site.js [--page FILE | --shared | --static PATH]");
}

if (require.main === module) main(process.argv.slice(2));

module.exports = {
  buildPage,
  buildSiteShellSource,
  pageValues,
};
